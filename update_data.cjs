const lines = csvData.trim().split('\n').slice(1);
const poets = [];

for (const line of lines) {
  // Parse CSV line
  // We can use a simple regex to split by comma, respecting quotes
  let matches = [];
  let current = '';
  let inQuotes = false;
  
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === ',' && !inQuotes) {
      matches.push(current);
      current = '';
    } else {
      current += char;
    }
  }
  matches.push(current);
  
  if (matches.length < 11) continue;
  
  const id = matches[0];
  const name = matches[1];
  const birth_year = parseInt(matches[2]);
  const death_year = parseInt(matches[3]);
  const era = matches[4];
  const lane = parseInt(matches[5]);
  const weight = parseInt(matches[6]);
  const tags = matches[7].split('|');
  const works_short = matches[8];
  const short_desc = matches[9];
  let full_text = matches[10];
  
  let works_content = [];
  if (full_text.startsWith('（')) {
    works_content = [full_text];
  } else {
    // Split by punctuation: ， 。 ？ ！ 、
    const sentences = full_text.match(/[^，。？！、]+[，。？！、]?/g);
    if (sentences) {
      works_content = sentences.map(s => s.trim()).filter(s => s.length > 0);
    } else {
      works_content = [full_text];
    }
  }
  
  poets.push({
    name,
    birth_year,
    death_year,
    era,
    lane,
    weight,
    tags,
    works_short,
    short_desc,
    works_content
  });
}

